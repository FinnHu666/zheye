-- FINNS 0.7.0 FINNS-18：文章草稿、发布生命周期。附加变更 + 回填，仅用于 PostgreSQL（H2 开发/测试靠 JPA 实体建表）。
-- 详见 docs/iterations/0.7.0/CONTRACT_CONTENT_PUBLISHING.md §2。执行前必须备份并在隔离 PostgreSQL 库演练（B7）；
-- 本脚本尚未在 PostgreSQL 实测。不支持回退旧程序包（沿用 REVIEW-D16-U3）。
-- 约束名 content_posts_moderation_state_check 为 V15 内联 CHECK 的 PostgreSQL 默认命名，演练时先 \d content_posts 核对。

create table article_drafts (
    id bigint generated by default as identity primary key,
    author_id bigint not null references user_accounts(id),
    post_id bigint unique references content_posts(id),
    title varchar(120) not null default '',
    summary varchar(280) not null default '',
    body text not null default '',
    version bigint not null default 1,
    last_request_id varchar(64),
    last_request_version bigint,
    last_request_hash varchar(64),
    legacy_state_id bigint,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null,
    constraint ck_article_draft_nonempty check (title <> '' or summary <> '' or body <> '')
);
create index ix_article_drafts_author on article_drafts (author_id, updated_at desc, id desc);

alter table content_posts add column updated_at timestamp with time zone;
alter table content_posts drop constraint if exists content_posts_moderation_state_check;
alter table content_posts add constraint content_posts_moderation_state_check check (moderation_state in ('VISIBLE', 'TAKEN_DOWN', 'WITHDRAWN'));

alter table review_audit_log drop constraint if exists review_audit_log_type_check;
alter table review_audit_log add constraint review_audit_log_type_check
    check (type in ('SUBMIT', 'APPROVE', 'REJECT', 'UPHOLD', 'OVERTURN', 'TAKE_DOWN', 'RESTORE', 'WITHDRAW', 'RULE_CREATE', 'RULE_UPDATE', 'RULE_DELETE', 'BATCH_RULES', 'IMPORT_RULES', 'NOTED', 'DELETE_DRAFT'));

-- A 已发布文章建稿
insert into article_drafts (author_id, post_id, title, summary, body, version, created_at, updated_at)
select p.author_id, p.id, p.title, p.summary, p.body, 1, p.created_at, p.created_at
from content_posts p
where p.type = 'ARTICLE' and not exists (select 1 from article_drafts d where d.post_id = p.id);

-- B 已发布文章的审核状态改键为稳定键 ARTICLE#<draftId>；缺状态的补一条历史基线状态
update review_content_state s
   set content_key = 'ARTICLE#' || (select d.id from article_drafts d where d.post_id = s.target_id), updated_at = now()
 where s.content_type = 'ARTICLE' and s.target_id is not null and s.content_key not like 'ARTICLE#%'
   and exists (select 1 from article_drafts d where d.post_id = s.target_id and d.author_id = s.author_id);

insert into review_content_state (author_id, content_type, content_key, target_id, attempts, generation, approved_once, legacy, created_at, updated_at)
select d.author_id, 'ARTICLE', 'ARTICLE#' || d.id, d.post_id, 0, 1, true, true, now(), now()
from article_drafts d
where d.post_id is not null
  and not exists (select 1 from review_content_state s where s.content_type = 'ARTICLE' and s.author_id = d.author_id and s.content_key = 'ARTICLE#' || d.id);

-- C 在途未发布提交按最新快照补建草稿（没有任何提交的空状态跳过；快照三项全空也跳过）
insert into article_drafts (author_id, post_id, title, summary, body, version, legacy_state_id, created_at, updated_at)
select s.author_id, null, left(coalesce(x.snap->>'title', ''), 120), left(coalesce(x.snap->>'summary', ''), 280), coalesce(x.snap->>'body', ''), x.snapshot_version, s.id, x.created_at, now()
from review_content_state s
join lateral (select r.snapshot_json::jsonb as snap, r.snapshot_version, r.created_at from review_submissions r where r.state_id = s.id order by r.id desc limit 1) x on true
where s.content_type = 'ARTICLE' and s.target_id is null and s.content_key not like 'ARTICLE#%'
  and (coalesce(x.snap->>'title', '') <> '' or coalesce(x.snap->>'summary', '') <> '' or coalesce(x.snap->>'body', '') <> '');

update review_content_state s set content_key = 'ARTICLE#' || d.id, updated_at = now()
  from article_drafts d where d.legacy_state_id = s.id;
alter table article_drafts drop column legacy_state_id;
