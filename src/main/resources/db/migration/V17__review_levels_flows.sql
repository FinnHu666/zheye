-- FINNS 0.7.0 FINNS-17 需规修订6 / 原型 R3：敏感三级、流转事件、低敏感留痕、规则标签。全部为附加或放宽变更。
-- 命中计数（attempts）与专题首次审批（approved_once 对判定的作用）不再使用，列保留不写，避免破坏性变更。

alter table sensitive_rules add column level varchar(8) not null default 'MEDIUM' check (level in ('LOW', 'MEDIUM', 'HIGH'));
alter table sensitive_rules add column tag varchar(30);
create index ix_sensitive_rules_tag on sensitive_rules (tag) where tag is not null;

alter table review_submissions add column kind varchar(8) not null default 'REVIEW' check (kind in ('REVIEW', 'RECHECK'));
alter table review_submissions add column level varchar(8) not null default 'MEDIUM';
alter table review_submissions add column flow_id bigint;
alter table review_submissions drop constraint if exists review_submissions_status_check;
alter table review_submissions add constraint review_submissions_status_check check (status in ('PENDING', 'APPROVED', 'REJECTED', 'UPHELD', 'OVERTURNED', 'INVALID'));

create table review_flows (
    id bigint generated by default as identity primary key,
    state_id bigint not null references review_content_state(id) on delete cascade,
    author_id bigint not null,
    content_type varchar(12) not null,
    title varchar(120) not null default '',
    snapshot_version bigint not null,
    level varchar(8) not null,
    status varchar(14) not null check (status in ('IN_REVIEW', 'PUBLISHED', 'AUTO_REJECTED', 'REJECTED', 'UPHELD', 'INVALID')),
    started_at timestamp not null
);
create index ix_review_flows_state on review_flows (state_id, started_at desc, id desc);
create index ix_review_flows_author on review_flows (author_id, started_at desc, id desc);

create table review_flow_events (
    id bigint generated by default as identity primary key,
    flow_id bigint not null references review_flows(id) on delete cascade,
    stage varchar(10) not null check (stage in ('SUBMIT', 'CHECK', 'ROUTE', 'REVIEW', 'RESULT')),
    title varchar(60) not null,
    note varchar(200) not null default '',
    detail varchar(400) not null default '',
    actor_id bigint,
    actor_name varchar(40),
    occurred_at timestamp not null
);
create index ix_review_flow_events_flow on review_flow_events (flow_id, occurred_at, id);

create table review_noted (
    id bigint generated by default as identity primary key,
    content_type varchar(12) not null,
    content_id bigint not null,
    author_id bigint not null,
    title varchar(120) not null default '',
    words varchar(400) not null,
    created_at timestamp not null,
    reviewed_by bigint,
    reviewed_by_name varchar(40),
    reviewed_at timestamp
);
create index ix_review_noted_time on review_noted (created_at desc, id desc);

alter table review_audit_log drop constraint if exists review_audit_log_type_check;
alter table review_audit_log add constraint review_audit_log_type_check
    check (type in ('SUBMIT', 'APPROVE', 'REJECT', 'UPHOLD', 'OVERTURN', 'TAKE_DOWN', 'RESTORE', 'WITHDRAW', 'RULE_CREATE', 'RULE_UPDATE', 'RULE_DELETE', 'BATCH_RULES', 'IMPORT_RULES', 'NOTED'));
