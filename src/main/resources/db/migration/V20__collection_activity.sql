create table collection_activity (
    id bigint generated by default as identity primary key,
    collection_id bigint not null references community_collections(id) on delete cascade,
    action varchar(24) not null,
    revision bigint not null,
    occurred_at timestamp with time zone not null default current_timestamp
);
create index idx_collection_activity on collection_activity(collection_id,id);
-- Preserve the original free text; only exact preset matches enter the structured field.
update community_collections c set wizard_metadata=json_build_object(
    'tags',json_build_array(),'category','','seoTitle','',
    'audiences',coalesce((select json_agg(trim(v.label) order by v.n) from unnest(string_to_array(c.audience,'、')) with ordinality v(label,n)
        where trim(v.label) in ('学生','职场人士','产品/运营','开发者','设计师','创业者','AI 爱好者','其他')),'[]'::json),
    'coverId',null,'sectionLayouts',json_build_array())::text
where wizard_metadata is null;
