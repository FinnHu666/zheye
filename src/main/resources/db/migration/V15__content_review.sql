-- FINNS 0.7.0 FINNS-17：内容敏感拦截、专题首次审批与下架。全部为附加变更；旧程序包忽略新列/新表继续运行。
-- 注意：旧程序包不认识 moderation_state，回退后被下架的内容会重新公开，也不做敏感检测（见 DESIGN_CONTENT_REVIEW.md §4；用户决定不支持回退旧包）。

alter table content_posts add column moderation_state varchar(10) not null default 'VISIBLE' check (moderation_state in ('VISIBLE', 'TAKEN_DOWN'));
alter table content_posts add column review_submission_id bigint;
alter table comments add column moderation_state varchar(10) not null default 'VISIBLE' check (moderation_state in ('VISIBLE', 'TAKEN_DOWN'));
alter table comments add column review_submission_id bigint;
alter table community_collections add column moderation_state varchar(10) not null default 'VISIBLE' check (moderation_state in ('VISIBLE', 'TAKEN_DOWN'));

create table sensitive_rules (
    id bigint generated by default as identity primary key,
    phrase varchar(40) not null,
    note varchar(200) not null default '',
    enabled boolean not null default true,
    deleted boolean not null default false,
    active_key varchar(160),
    version bigint not null default 1,
    created_by bigint references user_accounts(id) on delete set null,
    created_at timestamp not null,
    updated_at timestamp not null
);
create unique index ux_sensitive_rules_active on sensitive_rules (active_key) where active_key is not null;

create table review_content_state (
    id bigint generated by default as identity primary key,
    author_id bigint not null references user_accounts(id) on delete cascade,
    content_type varchar(12) not null check (content_type in ('ARTICLE', 'COMMENT', 'COLLECTION')),
    content_key varchar(80) not null,
    target_id bigint,
    attempts int not null default 0,
    generation bigint not null default 1,
    approved_once boolean not null default false,
    legacy boolean not null default false,
    created_at timestamp not null,
    updated_at timestamp not null,
    constraint ux_review_state_key unique (author_id, content_type, content_key)
);

create table review_submissions (
    id bigint generated by default as identity primary key,
    state_id bigint not null references review_content_state(id) on delete cascade,
    author_id bigint not null references user_accounts(id) on delete cascade,
    content_type varchar(12) not null,
    title varchar(120) not null default '',
    generation bigint not null,
    snapshot_json text not null,
    snapshot_version bigint not null,
    triggers varchar(30) not null,
    matched_phrases varchar(400) not null default '',
    attempts int not null,
    status varchar(10) not null check (status in ('PENDING', 'APPROVED', 'REJECTED', 'INVALID')),
    result_note varchar(200) not null default '',
    operator_id bigint,
    operator_name varchar(40),
    created_at timestamp not null,
    closed_at timestamp
);
create index ix_review_sub_status on review_submissions (status, created_at desc, id desc);
create index ix_review_sub_author on review_submissions (author_id, created_at desc, id desc);

create table review_receipts (
    state_id bigint not null references review_content_state(id) on delete cascade,
    request_id varchar(64) not null,
    response_json text not null,
    created_at timestamp not null,
    primary key (state_id, request_id)
);

create table review_audit_log (
    id bigint generated by default as identity primary key,
    type varchar(14) not null check (type in ('SUBMIT', 'APPROVE', 'REJECT', 'TAKE_DOWN', 'RESTORE', 'WITHDRAW', 'RULE_CREATE', 'RULE_UPDATE', 'RULE_DELETE')),
    outcome varchar(10) not null default 'SUCCESS' check (outcome in ('SUCCESS', 'REJECTED', 'FAILED')),
    operator_id bigint,
    operator_name varchar(40),
    author_id bigint,
    content_type varchar(12),
    content_id bigint,
    submission_id bigint,
    snapshot_version bigint,
    triggers varchar(30),
    phrase varchar(40),
    rule_enabled boolean,
    note varchar(200),
    result_message varchar(200),
    created_at timestamp not null
);
create index ix_review_audit_time on review_audit_log (created_at desc, id desc);

-- 内容审批权限：站长角色自动拥有；其他角色由管理员在角色页手动授予。
insert into role_permissions (role_id, permission)
select r.id, 'content.review' from roles r
where r.system_kind = 'OWNER'
  and not exists (select 1 from role_permissions x where x.role_id = r.id and x.permission = 'content.review');
