insert into collection_entries(collection_id,section_id,kind,sort_order,title,annotation,body,post_id,external_url,created_at,updated_at)
select cp.collection_id,s.id,'POST',
       cast(row_number() over(partition by cp.collection_id order by cp.created_at desc,cp.post_id desc)-1 as integer),
